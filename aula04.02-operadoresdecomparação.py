## O que são "OPERADORES DE COMPARAÇÃO"?
##
## são usados para comparar valores
## eles verificam relações entre dois valores
## o resultado de uma comparação sempre será : TRUE or FALSE

## TABELA DE OPERADORES DE COMPARAÇÃO:

##   operador                    significado                    exemplo

##    ==                          "igual a"                     10 == 10
##    !=                          "diferente de"                10 != 5
##    >                           "maior que"                  10 > 5
##    <                           "menor que"                  5 < 10
##    >=                          "maior ou igual que"         10 >= 10
#     <=                          "menor ou igual que"         5 <= 10

A = 10
B = 20
print ( A == B )