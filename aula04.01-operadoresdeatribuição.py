## aula 17/08 - OPERADORES DE ATRIBUIÇÃO
##
## = ---- atribuição simples
## += ---- soma e atribui
## -= ---- subtrai e atribui
## *= ---- multiplica e atribui
## /= ---- divide e atribui
## %= ---- resto da divisão e atribui
## **= ---- potencia e atribui
## //= ---- divisao e atribui

## exemplos:

somaeatribui = 10;
somaeatribui += 10;
print ('Soma e Atribui:', somaeatribui);

subtraieatribui = 10;
subtraieatribui -= 10;
print ('Subtrai e Atribui:', subtraieatribui);

multiplicaeatribui = 10;
multiplicaeatribui *= 10;
print ('Multiplica e Atribui:', multiplicaeatribui);

divideeatribui = 10;
divideeatribui /= 10;
print ('Divide e Atribui:', divideeatribui);

restodadivisaoeatribui = 10;
restodadivisaoeatribui %= 10;
print ('Resto da divisão e Atribui:', restodadivisaoeatribui);

potenciaeatribui = 10;
potenciaeatribui **= 10;
print ('Potencia e Atribui:', potenciaeatribui);

divisaoeatribui = 10;
divisaoeatribui //= 10;
print ('Divisão e Atribui:', divisaoeatribui);